package com.tfassbender.shoppinglist.application.list

import com.tfassbender.shoppinglist.application.port.SequenceCounter
import com.tfassbender.shoppinglist.application.port.ShoppingListRepository
import com.tfassbender.shoppinglist.application.space.SpaceAccess
import com.tfassbender.shoppinglist.application.space.SpaceLocks
import com.tfassbender.shoppinglist.domain.DomainException
import com.tfassbender.shoppinglist.domain.ErrorKind
import com.tfassbender.shoppinglist.domain.list.ListChange
import com.tfassbender.shoppinglist.domain.list.ListId
import com.tfassbender.shoppinglist.domain.list.ShoppingList
import com.tfassbender.shoppinglist.domain.space.SpaceId
import com.tfassbender.shoppinglist.domain.user.UserId
import jakarta.enterprise.context.ApplicationScoped
import java.time.Clock
import java.util.UUID

/**
 * Lists and items of a space. Members may do everything except deleting lists (owner only). Every
 * mutation runs under the space lock and stamps a fresh space sequence number.
 */
@ApplicationScoped
class ShoppingListService(
    private val lists: ShoppingListRepository,
    private val sequence: SequenceCounter,
    private val access: SpaceAccess,
    private val locks: SpaceLocks,
    private val clock: Clock,
) {

    fun lists(userId: UserId, spaceId: SpaceId): List<ShoppingList> {
        access.requireMember(spaceId, userId)
        return lists.findBySpace(spaceId).filterNot { it.deleted }.sortedBy { it.createdAt }
    }

    fun get(userId: UserId, spaceId: SpaceId, listId: ListId): ShoppingList {
        access.requireMember(spaceId, userId)
        return load(spaceId, listId)
    }

    /** [listId] may be generated by the client (offline creation); otherwise a UUID is used. */
    fun create(userId: UserId, spaceId: SpaceId, name: String, listId: ListId? = null): ShoppingList =
        locks.withLock(spaceId) {
            access.requireMember(spaceId, userId)
            val id = listId ?: ListId(UUID.randomUUID().toString())
            if (lists.findById(spaceId, id) != null) {
                throw DomainException(ErrorKind.CONFLICT, "LIST_EXISTS", "List ${id.value} already exists")
            }
            val list = ShoppingList.create(id, spaceId, name, sequence.next(spaceId), clock.instant())
            lists.save(list)
            list
        }

    fun delete(userId: UserId, spaceId: SpaceId, listId: ListId) {
        locks.withLock(spaceId) {
            access.requireOwner(spaceId, userId)
            lists.save(load(spaceId, listId).markDeleted(sequence.next(spaceId)))
        }
    }

    /** Applies changes in order, atomically: if one fails, none is saved. */
    fun applyChanges(userId: UserId, spaceId: SpaceId, listId: ListId, changes: List<ListChange>): ShoppingList =
        locks.withLock(spaceId) {
            access.requireMember(spaceId, userId)
            val seq = sequence.next(spaceId)
            val now = clock.instant()
            val updated = changes.fold(load(spaceId, listId)) { list, change -> list.apply(change, seq, now) }
            lists.save(updated)
            updated
        }

    fun apply(userId: UserId, spaceId: SpaceId, listId: ListId, change: ListChange): ShoppingList =
        applyChanges(userId, spaceId, listId, listOf(change))

    private fun load(spaceId: SpaceId, listId: ListId): ShoppingList {
        val list = lists.findById(spaceId, listId)
        if (list == null || list.deleted) throw ShoppingList.listNotFound()
        return list
    }
}
